def test_two_different_players_cannot_occupy_the_same_formation_slot():
    engine = create_engine("sqlite://", poolclass=StaticPool)
    Base.metadata.create_all(engine)
    with Session(engine) as db:
        home, away = Team(name="Slot Home"), Team(name="Slot Away")
        db.add_all([home, away])
        db.flush()
        db.add_all([
            Player(team_id=home.id, name="Home One", position="Defender"),
            Player(team_id=home.id, name="Home Two", position="Defender"),
        ])
        db.flush()
        players = list(db.query(Player).order_by(Player.id))
        request = ReportRequest.model_validate({
            "home_team_id": home.id,
            "away_team_id": away.id,
            "formation_by_side": {"home": "4-3-3", "away": "4-4-2"},
            "players": [
                {"player_id": players[0].id, "side": "home", "formation_slot": 0, "position": {"x": 10, "y": 30}},
                {"player_id": players[1].id, "side": "home", "formation_slot": 0, "position": {"x": 20, "y": 60}},
            ],
        })
        with pytest.raises(ReportValidationError, match="formation slot"):
            generate_tactical_report(db, request)
    Base.metadata.drop_all(engine)
    engine.dispose()


