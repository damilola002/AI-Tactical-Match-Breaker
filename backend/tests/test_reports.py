def test_report_api_returns_evidence_linked_deterministic_report(client):
    first = client.post("/api/analysis/reports", json=_payload())
    second = client.post("/api/analysis/reports", json=_payload())
    assert first.status_code == second.status_code == 200
    report = first.json()
    assert report == second.json()
    assert report["report_mode"] == "deterministic_mock"
    assert "not generated by a real AI model" in report["report_notice"]
    assert report["scenario"]["placed_player_count"] == {"home": 1, "away": 1}
    references = {item["id"] for item in report["evidence_refs"]}
    assert all(set(item["evidence_ids"]) <= references for item in report["observations"])
    assert all(set(item["evidence_ids"]) <= references for item in report["recommendations"])
    assert all(item["id"].startswith("historical_match:") for item in report["evidence_refs"] if item["kind"] == "historical_match")
    assert all("." not in item["id"].split(":")[-1] for item in report["evidence_refs"] if item["kind"] == "scenario_metric")


