def test_report_is_deterministic_and_does_not_persist_rows():
    engine = create_engine("sqlite://", poolclass=StaticPool, connect_args={"check_same_thread": False})
    Base.metadata.create_all(engine)
    with Session(engine) as db:
        home, away = Team(id=1, name="Home Demo"), Team(id=2, name="Away Demo")
        db.add_all([home, away])
        db.flush()
        db.add_all([
            Player(id=1, team_id=1, name="Home Player", position="Defender"),
            Player(id=2, team_id=2, name="Away Player", position="Forward"),
        ])
        db.flush()
        db.add_all([
            Match(id=1, home_team_id=1, away_team_id=2, kickoff_at=datetime(2026, 1, 1), home_score=1, away_score=0),
            Match(id=2, home_team_id=1, away_team_id=2, kickoff_at=datetime(2026, 2, 1)),
            MatchPlayer(match_id=1, player_id=1, team_id=1, distance_covered_meters=Decimal("12345.50"), sprint_count=7),
            MatchPlayer(match_id=1, player_id=2, team_id=2, distance_covered_meters=Decimal("11000.00"), sprint_count=4),
        ])
        db.commit()
        models = (Team, Player, Match, MatchPlayer)
        before = {model.__tablename__: db.scalar(select(func.count()).select_from(model)) for model in models}
        request = ReportRequest.model_validate(_payload())
        first = generate_tactical_report(db, request).model_dump(mode="json")
        second = generate_tactical_report(db, request).model_dump(mode="json")
        after = {model.__tablename__: db.scalar(select(func.count()).select_from(model)) for model in models}
        assert first == second
        assert before == after
