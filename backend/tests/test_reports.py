def test_report_renders_recommendations_from_validated_insight_claims_only():
    engine = create_engine("sqlite://", poolclass=StaticPool, connect_args={"check_same_thread": False})
    Base.metadata.create_all(engine)
    with Session(engine) as db:
        home, away = Team(id=1, name="Home Shape"), Team(id=2, name="Away Shape")
        db.add_all([home, away])
        db.flush()
        db.add_all([
            Player(id=1, team_id=1, name="Home Defender", position="Defender"),
            Player(id=2, team_id=1, name="Home Midfielder", position="Midfielder"),
            Player(id=3, team_id=2, name="Away Forward", position="Forward"),
        ])
        db.commit()
        request = ReportRequest.model_validate({
            "home_team_id": 1, "away_team_id": 2,
            "formation_by_side": {"home": "4-3-3", "away": "4-4-2"},
            "players": [
                {"player_id": 1, "side": "home", "formation_slot": 0, "position": {"x": 10, "y": 30}},
                {"player_id": 2, "side": "home", "formation_slot": 1, "position": {"x": 60, "y": 60}},
                {"player_id": 3, "side": "away", "formation_slot": 0, "position": {"x": 80, "y": 50}},
            ],
        })
        report = generate_tactical_report(db, request).model_dump(mode="json")
        assert report["recommendations"]
        for recommendation in report["recommendations"]:
            assert recommendation["claim"]["claim_type"] == "scenario_insight"
            assert recommendation["evidence_ids"] == [recommendation["claim"]["evidence_id"]]
            assert recommendation["id"] == f"recommendation:{recommendation['claim']['evidence_id']}"
            if recommendation["claim"]["category"] == "line_spacing":
                assert "Review Home Shape's current defensive-to-midfield separation" in recommendation["text"]
            else:
                assert recommendation["text"].startswith("Review ")

        class MetricProvider:
            def generate(self, context):
                value = context["metrics"]["home"]["widthMeters"]
                claim = {
                    "claim_type": "scenario_metric",
                    "evidence_id": "scenario_metric:home:width_meters",
                    "side": "home", "team_id": 1, "metric_key": "width_meters",
                    "player_ids": [], "value": value,
                }
                return {
                    "observations": [{"claim": claim, "confidence": "high"}],
                    "recommendations": [{"claim": claim}],
                }

        metric_report = generate_tactical_report(db, request, provider=MetricProvider()).model_dump(mode="json")
        assert metric_report["observations"][0]["claim"]["metric_key"] == "width_meters"
        assert "pitch width" in metric_report["recommendations"][0]["text"]
    Base.metadata.drop_all(engine)
    engine.dispose()


